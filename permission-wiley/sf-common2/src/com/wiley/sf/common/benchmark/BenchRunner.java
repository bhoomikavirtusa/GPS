package com.wiley.sf.common.benchmark;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.Timestamp;

import com.wiley.sf.common.config.PropertiesUtil;
import com.wiley.sf.common.sql.SimpleDBConnect;


/**
 * Runs benchmarks in a thread and inserts results into a database.
 *
 * @since   JDK 1.5
 * @version $Id: BenchRunner.java,v 1.8 2010-08-31 23:38:27 smarkoff Exp $
 * @author  Steve Markoff
 */
public class BenchRunner {

    private static final int DEFAULT_INTERVAL_MIN = 10;

    public static void main(String [] args) throws Exception {
        if (args.length < 1) {
            System.err.println("usage: <properties file>");
            System.exit(1);
        }

        BenchRunner runner = new BenchRunner(args[0]);
        runner.go();
    }


    private final SimpleDBConnect dbConnect;
    private Bench [] benchArray;
    private final String environmentName;
    private final long intervalMS;


    public BenchRunner(String propertiesFileName) throws Exception {
        dbConnect = SimpleDBConnect.create(propertiesFileName);  // throws 4 exceptions
        // get a test connection
        Connection con = dbConnect.getConnection();
        con.close();

        PropertiesUtil props = new PropertiesUtil(propertiesFileName);
        String fileIODir = props.getString("fileIOBench.dir");
        environmentName = props.getString("environment.name");
        intervalMS = 60 * 1000 * props.getInt("intervalMin", DEFAULT_INTERVAL_MIN);

        benchArray = new Bench[3];
        benchArray[0] = new IntBench();
        benchArray[1] = new MemoryBench();
        benchArray[2] = new FileIOBench(fileIODir);
    }

    private void go() throws Exception {
        while (true) {
            long lastStartTime = System.currentTimeMillis();

            for (Bench bench : benchArray) {
                doBench(bench);
            }

            while (true) {
                long interval = System.currentTimeMillis() - lastStartTime;
                if (interval >= intervalMS) {
                    break;
                }
                try { Thread.sleep(1000); }
                catch (InterruptedException ex) { }
            }
        }
    }

    private void doBench(Bench bench) throws Exception {
        long startTime = System.currentTimeMillis();
        int score = bench.bench();
        long completeTime = System.currentTimeMillis();
        long timeMS = completeTime - startTime;

        String className = bench.getClass().getName();
        int index = className.lastIndexOf('.');
        if (index != -1) {
            className = className.substring(index + 1);
        }

        Connection con = dbConnect.getConnection();
        con.setAutoCommit(true);

        String sql = "insert into benchmark (started, completed, time_ms, environment, type, score) values (?, ?, ?, ?, ?, ?)";
        PreparedStatement ps = con.prepareStatement(sql);
        ps.setTimestamp(1, new Timestamp(startTime));
        ps.setTimestamp(2, new Timestamp(completeTime));
        ps.setLong(3, timeMS);
        ps.setString(4, environmentName);
        ps.setString(5, className);
        ps.setInt(6, score);
        ps.executeUpdate();
        ps.close();

        con.close();
    }
}

